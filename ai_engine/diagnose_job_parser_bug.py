# ---------------------------------------------------------------------
# Monkey-patch requests.post ONLY inside ai_engine.services.llm_service's
# already-imported `requests` reference, for THIS PROCESS ONLY. We call
# the REAL requests.post underneath and only observe start/end + payload
# + response -- never modify, never fake a value.
# ---------------------------------------------------------------------
from ai_engine.services import llm_service as _llm_service_module

_REAL_POST = _requests_module.post
_CAPTURED_CALLS = []


def _spy_post(url, json=None, timeout=None, **kwargs):
    entry = {
        "url": url,
        "payload": json,
        "timeout": timeout,
    }
    try:
        response = _REAL_POST(url, json=json, timeout=timeout, **kwargs)
        entry["http_status"] = response.status_code
        entry["raw_text"] = response.text
        try:
            entry["response_json"] = response.json()
        except Exception as parse_err:
            entry["response_json"] = None
            entry["response_json_parse_error"] = repr(parse_err)
        entry["exception"] = None
        _CAPTURED_CALLS.append(entry)
        return response
    except Exception as e:
        entry["http_status"] = None
        entry["raw_text"] = None
        entry["response_json"] = None
        entry["exception"] = repr(e)
        _CAPTURED_CALLS.append(entry)
        raise


_llm_service_module.requests.post = _spy_post

# ---------------------------------------------------------------------
# Also capture the exact final prompt string analyze_job_description()
# builds, WITHOUT changing its behavior: we wrap generate_json (the
