from ai_engine.services.llm_job_parser import analyze_job_description


def _sha256(text):
    return hashlib.sha256(text.encode("utf-8")).hexdigest()[:16]


def _dump_call(label, call, prompt):
    print(f"\n----- {label}: captured HTTP call -----")
    print(f"len(prompt)        : {len(prompt)}")
    print(f"prompt sha256[:16]  : {_sha256(prompt)}")
    print(f"repr(prompt)[:300]  : {repr(prompt)[:300]}...")
    if call is None:
        print("!! NO requests.post call was captured for this run !!")
        return
    print(f"payload.model       : {call['payload'].get('model') if call['payload'] else None}")
    print(f"payload.format      : {call['payload'].get('format') if call['payload'] else None}")
    print(f"payload.stream      : {call['payload'].get('stream') if call['payload'] else None}")
    print(f"payload prompt len  : {len(call['payload'].get('prompt', '')) if call['payload'] else None}")
    print(f"http_status         : {call['http_status']}")
    print(f"exception           : {call['exception']}")
    if call.get("response_json") is not None:
        raw_response_field = call["response_json"].get("response", "")
        print(f"data['response']    : {raw_response_field!r}")
        print(f"len(data['response']): {len(raw_response_field)}")
        try:
            parsed = json.loads(raw_response_field) if raw_response_field else None
            print(f"json.loads(data['response']) -> {parsed!r}")
        except Exception as e:
            print(f"json.loads(data['response']) RAISED: {e!r}")
        # Other Ollama fields that can reveal truncation/early-stop
        for k in ("done", "done_reason", "total_duration", "eval_count", "prompt_eval_count"):
            if k in call["response_json"]:
                print(f"data['{k}']".ljust(22) + f": {call['response_json'][k]!r}")
    else:
        print(f"raw_text[:500]      : {(call.get('raw_text') or '')[:500]!r}")


def run_case(label, description_text):
    _CAPTURED_CALLS.clear()
    _CAPTURED_PROMPTS.clear()

    print(f"\n{'='*70}\n{label}\n{'='*70}")
    print(f"description bytes  : {description_text.encode('utf-8')!r}")
    print(f"len(description)   : {len(description_text)}")

    result = analyze_job_description(description_text)

    print(f"\nFINAL RESULT analyze_job_description() -> {result!r}")

    prompt = _CAPTURED_PROMPTS[0] if _CAPTURED_PROMPTS else "<no prompt captured>"
    call = _CAPTURED_CALLS[0] if _CAPTURED_CALLS else None
    _dump_call(label, call, prompt)

    return result, prompt, call


