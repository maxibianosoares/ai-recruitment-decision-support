from ai_engine.services import llm_job_parser as _llm_job_parser_module

_REAL_GENERATE_JSON = _llm_job_parser_module.generate_json
_CAPTURED_PROMPTS = []


def _spy_generate_json(prompt, default=None):
    _CAPTURED_PROMPTS.append(prompt)
    return _REAL_GENERATE_JSON(prompt=prompt, default=default)


_llm_job_parser_module.generate_json = _spy_generate_json

# NOW import the real, unmodified function under test (after patching its
